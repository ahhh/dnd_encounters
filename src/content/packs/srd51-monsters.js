// SRD 5.1 creatures.
//
// A curated cross-section rather than the whole SRD bestiary: every challenge
// rating from 0 to 17, every creature type the generator filters on, and both
// weapon-users and spellcasters at several tiers.
//
// The important property is that nothing here is prose the generator has to
// parse. `attack.bonus`, `damage[].dice`, `save.dc` and `recharge` are fields,
// so a downstream tool reads a number rather than a sentence -- and the CR
// evaluator can re-derive each creature's rating from the same fields, which is
// exactly how `tools/verify.mjs cr` keeps the evaluation model honest.

/** "2d10+6" -> {dice, bonus, type, average}. Averages are precomputed here. */
const dmg = (expr, type) => {
  const m = /^(\d+)d(\d+)(?:\+(\d+))?$/.exec(expr) || [];
  if (!m.length) return { dice: null, bonus: Number(expr) || 0, type, average: Number(expr) || 0 };
  const count = Number(m[1]);
  const sides = Number(m[2]);
  const bonus = m[3] ? Number(m[3]) : 0;
  return { dice: `${count}d${sides}`, bonus, type, average: Math.floor(count * (sides + 1) / 2) + bonus };
};

/** A melee or ranged weapon attack action. */
const atk = (name, bonus, reachOrRange, damage, o = {}) => ({
  id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
  name,
  actionType: 'action',
  attack: typeof reachOrRange === 'number'
    ? { bonus, reach: reachOrRange }
    : { bonus, range: { normal: reachOrRange[0], long: reachOrRange[1] } },
  damage,
  effects: o.effects || [],
  ...(o.desc ? { description: o.desc } : {}),
  ...(o.primary ? { primary: true } : {}),
  ...(o.save ? { save: o.save } : {}),
});

/** An area or saving-throw action. */
const area = (name, save, damage, o = {}) => ({
  id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
  name,
  actionType: 'action',
  save,
  damage,
  effects: o.effects || [],
  ...(o.desc ? { description: o.desc } : {}),
  ...(o.recharge ? { recharge: { formula: o.recharge } } : {}),
  ...(o.uses ? { uses: o.uses } : {}),
});

/** Multiattack, carrying the count the CR evaluator multiplies damage by. */
const multi = (desc, count) => ({
  id: 'multiattack', name: 'Multiattack', actionType: 'action',
  description: desc, multiattackCount: count, effects: [],
});

const S = (str, dex, con, int, wis, cha) => ({ str, dex, con, int, wis, cha });
const walk = (n) => [{ type: 'walk', value: n }];
const sp = (...pairs) => pairs.map(([type, value]) => ({ type, value }));
const dark = (range) => [{ type: 'darkvision', range }];

